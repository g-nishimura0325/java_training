class rennsyuu1
{
    public static void main(String[] args)
    {
        int num1 = 0-4;
        double num2 = 3.14*2;
        double num3 = 5/3;
        int num4 = 30%7;
        double num5 = (7+32)/5;

        System.out.println("0-4は"+num1+"です。");
        System.out.println("3.14*2は"+num2+"です。");
        System.out.println("5/3は"+num3+"です。");
        System.out.println("20/7のあまりの数は"+num4+"です。");
        System.out.println("(7+32)/5は"+num5+"です。");
    }
}